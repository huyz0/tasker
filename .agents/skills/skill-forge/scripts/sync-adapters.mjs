#!/usr/bin/env node
/**
 * Generates the Claude Code adapter layer from the canonical `.agents/` tree.
 *
 * Codex and Antigravity read `.agents/` natively; Claude Code reads `.claude/`
 * only. Rather than maintain two copies of every playbook — which drift — the
 * `.claude/` files are thin forwarders generated from `.agents/` and never
 * hand-edited.
 *
 *   node .agents/skills/skill-forge/scripts/sync-adapters.mjs
 *   node .agents/skills/skill-forge/scripts/sync-adapters.mjs --check
 *
 * Exit codes: 0 in sync (or written) · 1 out of sync under --check · 2 failure.
 */

import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, rmSync, statSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../../..');
const CHECK = process.argv.includes('--check');

const SKILLS = '.agents/skills';
const WORKFLOWS = '.agents/workflows';
const C_COMMANDS = '.claude/commands';
const C_SKILLS = '.claude/skills';

const GENERATED = '<!-- generated by skill-forge sync — edit .agents/, not this file -->';

const abs = (rel) => join(ROOT, rel);
const read = (rel) => readFileSync(abs(rel), 'utf8');
const mds = (rel) => (existsSync(abs(rel)) ? readdirSync(abs(rel)).filter((n) => n.endsWith('.md')) : []);
const subdirs = (rel) =>
  existsSync(abs(rel)) ? readdirSync(abs(rel)).filter((n) => statSync(join(abs(rel), n)).isDirectory()) : [];

function frontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!m) return { fm: {}, body: text };
  const fm = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z][\w-]*):\s*(.*)$/);
    if (kv) fm[kv[1]] = kv[2].trim().replace(/^["']|["']$/g, '');
  }
  return { fm, body: m[2] };
}

const changed = [];
function emit(rel, content) {
  const current = existsSync(abs(rel)) ? read(rel) : null;
  if (current === content) return;
  changed.push(rel);
  if (CHECK) return;
  mkdirSync(dirname(abs(rel)), { recursive: true });
  writeFileSync(abs(rel), content);
}

// ── Commands: one per workflow ───────────────────────────────────────────────
for (const file of mds(WORKFLOWS).sort()) {
  const text = read(`${WORKFLOWS}/${file}`);
  const { fm, body } = frontmatter(text);
  const target = body.match(/\.agents\/skills\/([a-z0-9-]+)\/SKILL\.md/)?.[1];
  if (!target) continue;

  const autonomous = /AUTONOMOUS/i.test(body);
  const takesArg = /\*\*Argument\*\*:\s*(.+)/.exec(body)?.[1]?.trim();

  // The command palette is what a human browses, and it used to read
  // "Milestone Deliver" — the workflow's title, which restates its own name and
  // routes nothing. The skill's description is the one written to be routed on,
  // so take it from there.
  //
  // Only the "what it does" half, though. Claude Code loads skill *and* command
  // descriptions, so copying the whole thing pays twice for the same text — the
  // trailing "Use when …" trigger is what the model routes on and it is already
  // in the skill entry. A palette you are deliberately browsing needs the what.
  const skillPath = `${SKILLS}/${target}/SKILL.md`;
  const skillDesc = existsSync(abs(skillPath)) ? frontmatter(read(skillPath)).fm.description : null;
  const what = skillDesc?.split(/(?<=\.)\s+(?=Use\b)/)[0]?.trim();
  const description = what
    ? autonomous
      ? `Autonomous — ${what[0].toLowerCase()}${what.slice(1)}`
      : what
    : (fm.description ?? target);

  const mode = autonomous
    ? 'exactly in **AUTONOMOUS** mode: do not ask questions. Follow the stopping\nrules in `.agents/protocols/autonomy.md` — never mark work complete whose\nverification has not actually passed, and stop rather than continue past two\nconsecutive failures on the same unit.'
    : 'exactly in **INTERACTIVE** mode: use AskUserQuestion to confirm before each\nirreversible step, one question at a time.';

  const lines = [
    '---',
    `description: ${description}`,
    ...(takesArg ? [`argument-hint: "${takesArg.replace(/"/g, "'")}"`] : []),
    '---',
    '',
    GENERATED,
    '',
    `Read \`.agents/skills/${target}/SKILL.md\` — the portable, agent-agnostic source`,
    'of truth for this repository — and execute its instructions',
    mode,
    ...(takesArg ? ['', 'Arguments: $ARGUMENTS'] : []),
    '',
  ];
  emit(`${C_COMMANDS}/${file}`, lines.join('\n'));
}

// ── Skills: one adapter per skill ────────────────────────────────────────────
for (const name of subdirs(SKILLS).sort()) {
  const rel = `${SKILLS}/${name}/SKILL.md`;
  if (!existsSync(abs(rel))) continue;
  const { fm } = frontmatter(read(rel));

  emit(
    `${C_SKILLS}/${name}/SKILL.md`,
    [
      '---',
      `name: ${fm.name ?? name}`,
      `description: ${fm.description ?? ''}`,
      '---',
      '',
      GENERATED,
      '',
      `The full playbook lives at \`.agents/skills/${name}/SKILL.md\` — the portable,`,
      'agent-agnostic source of truth for this repository.',
      '',
      'Read that file and execute it exactly. Default to interactive mode unless the',
      'caller explicitly asked for autonomous execution.',
      '',
    ].join('\n')
  );
}

// ── Prune orphans ────────────────────────────────────────────────────────────
const workflowNames = new Set(mds(WORKFLOWS));
for (const file of mds(C_COMMANDS)) {
  if (workflowNames.has(file)) continue;
  changed.push(`${C_COMMANDS}/${file} (orphan, removed)`);
  if (!CHECK) rmSync(abs(`${C_COMMANDS}/${file}`));
}
const skillNames = new Set(subdirs(SKILLS));
for (const name of subdirs(C_SKILLS)) {
  if (skillNames.has(name)) continue;
  changed.push(`${C_SKILLS}/${name} (orphan, removed)`);
  if (!CHECK) rmSync(abs(`${C_SKILLS}/${name}`), { recursive: true });
}

// ── Report ───────────────────────────────────────────────────────────────────
if (!changed.length) {
  console.log('✓ adapters in sync');
  process.exit(0);
}
console.log(`${CHECK ? '✗ out of sync' : '✓ synced'} (${changed.length})`);
for (const c of changed) console.log(`  ${CHECK ? '!' : '+'} ${c}`);
process.exit(CHECK ? 1 : 0);
